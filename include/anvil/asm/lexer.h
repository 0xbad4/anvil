#pragma once

#include "base.h"
#include <algorithm>
#include <cctype>
#include <istream>


namespace anvil::s {
    class Lexer : public BaseObj {
        public:
            Lexer(source src) : m_source(src) { }

            /**
             * @brief Tokenizes the given source code and returns an error code
             * @param source The source code to tokenize
             * @return @c true if success.
            */
            bool tokenize() noexcept {
                if (!m_source.data | !m_source.size) {
                    report("Invalid source code", {0, 0});
                    return false;
                }

                while(valid()) {
                    // set token starting position
                    m_start = m_current;

                    // handle token
                    handle();
                }

                // end of file token
                insert(token_type::EOF_);

                return ok();
            }

            /**
             * @brief Returns the vector @c tokens_t of tokens generated by the lexer
             */
            const tokens_t& tokens() const noexcept {
                return m_tokens;
            }

        protected:
            token_pos m_pos {0, 0};
            size_t   m_start   = 0;
            size_t   m_current = 0;
            source    m_source;
            tokens_t  m_tokens;

            void handle() noexcept {
                char chr = advance();

                switch (chr) {
                    case ';':
                        handle_comment();
                        break;
                    case ':':
                        insert(token_type::COLON);
                        break;
                    case '[':
                        insert(token_type::LBRACKET);
                        break;
                    case ']':
                        insert(token_type::RBRACKET);
                        break;
                    case '(':
                        insert(token_type::LPARENTH);
                        break;
                    case ')':
                        insert(token_type::RPARENTH);
                        break;
                    case ',':
                        insert(token_type::COMMA);
                        break;
                    case '+':
                        insert(token_type::PLUS);
                        break;
                    case '*':
                        insert(token_type::STAR);
                        break;
                    case '&':
                        insert(token_type::AMP);
                        break;
                    case ' ':
                    case '\r':
                    case '\t':
                        // ignore whitespace.
                        break;
                    case '\n':
                        handle_new_line();
                        break;
                    case '#':
                    case '-':
                        handle_number(chr);
                        break;
                    default:
                        default_char_case(chr);
                }
            }

            void default_char_case(char chr) noexcept {
                if (utils::is_alpha(chr) || chr == '%') {
                    handle_identifier();
                }
                else if (utils::is_digit(chr)) {
                    handle_number(chr);
                }
                else {
                    report("unexpected character '" + std::string(1, chr) + "'", m_pos);
                }
            }

            // ------------------- handlers -------------------
            void handle_new_line() noexcept {
                if (!m_tokens.empty() && m_tokens.back().type != token_type::EOL) {
                    insert(token_type::EOL);
                }

                new_line();
            }

            void handle_identifier() noexcept {
                // consume alpha numeric chars + underscore
                while(utils::is_almun(peek())) {
                    (void)advance();
                }

                // get identifier's value
                std::string value = current_value();

                // since we are case insensitive, convert to lower case for comparison
                std::string lower = value;
                std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
                

                if (value[0] == '#' || lower == "len") {
                    // NOTE: convert all to lower to support case insensitive extension names
                    insert(token_type::EXT, value[0] == '#' ? value.erase(0, 1) : value);
                }
                else if (lower == "m") {
                    insert(token_type::KW_M, value);
                }
                else if (lower == "a" || lower == "%a") {
                    insert(token_type::REG_A, value);
                }
                else if (lower == "x" || lower == "%x") {
                    insert(token_type::REG_X, value);
                }                
                else if (data::MNEMONICS.contains(lower)) {
                    insert(token_type::MNEMONIC, value);  // real case value is preserved in the token
                }
                // if not a mnemonic it is a label
                else {
                    // Label name cannot start with "%"
                    // NOTE: reached this point because of `default_char_case`.
                    if (lower[0] == '%') {
                        report("invalid label name '" + value + "'; label names cannot start with '%'", m_pos);
                    }
                    else {
                        insert(token_type::IDENTIFIER, value);
                    }
                }
            }

            void handle_number(char chr) noexcept {
                // can be: K, -K, 0xK, #K, #-K, #name (extension)
                bool is_hex = false;
                bool has_hash = false;
                size_t digits = 0;

                if (chr == '#') {
                    has_hash = true;

                    // `#proto` is an extension name, same token as `proto`
                    if (utils::is_alpha(peek())) {
                        handle_identifier();
                        return;
                    }

                    if (peek() == '-') {
                        (void)advance();  // skip '-'
                    }
                }
                // hex: 0xK  (a plain 0 is just a decimal number)
                else if (chr == '0' && (peek() == 'x' || peek() == 'X')) {
                    (void)advance();  // skip 'x'
                    is_hex = true;
                }
                else if (chr == '-') {
                    // sign only, the digits follow
                }
                else {
                    digits = 1;  // chr itself is the first digit
                }

                while (utils::is_digit(peek()) || (is_hex && std::isxdigit(peek()))) {
                    (void)advance();
                    digits++;
                }

                // "0x", "#-", "-" with nothing after them
                if (digits == 0) {
                    if (is_hex) {
                        report("expected hex digits after '0x'", m_pos);
                    }
                    else if (has_hash) {
                        report("expected a number or an extension name after '#'", m_pos);
                    }
                    else {
                        report("expected a number after '-'", m_pos);
                    }
                    return;
                }

                // a letter glued to a number: 0x1G, 12ab
                if (utils::is_almun(peek())) {
                    report(std::string("invalid digit '") + peek() + "' in number", m_pos);

                    // swallow the rest of the word so it doesn't become a second token
                    while (utils::is_almun(peek())) {
                        (void)advance();
                    }
                    return;
                }

                insert(token_type::NUMBER, current_value());
            }

            void handle_comment() noexcept {
                // keep consuming until EOL | EOF hit
                while (peek() != '\n' && !is_end()) {
                    (void)advance();
                }
            }

            // ------------------- cursor ctrl -------------------
            char advance() noexcept {
                m_pos.col += 1;
                return m_source.data[m_current++];
            }

            char peek(size_t n = 0) noexcept {
                if (is_end()) {
                    return '\0';
                }
                return m_source.data[m_current + n];
            }

            void new_line() noexcept {
                m_pos.col  = 0;
                m_pos.line += 1;
            }

            // ------------------- tokens -------------------
            void insert(token_type t, std::string lexeme = "") noexcept {
                m_tokens.push_back(token(t, m_pos, lexeme));
            }

            // ------------------- helpers -------------------
            bool is_end() noexcept {
                return (m_current >= m_source.size);
            }

            std::string current_value() noexcept {
                return std::string(this->m_source.data + m_start, m_current - m_start);
            }

            bool valid() noexcept {
                return m_current < m_source.size;
            }
    };
} // namespace anvil
